//! `readme` / `readme-examples-js` subcommands — one source for every published README.
//!
//! `docs/readme/README.src.md` (plus the fragments next to it) is the only place
//! the READMEs are written. `cargo xtask readme` renders it once per channel:
//!
//! | Channel  | Output                           | Published on              |
//! |----------|----------------------------------|---------------------------|
//! | `github` | `README.md`                      | GitHub front page         |
//! | `rust`   | `crates/semiflow/README.md`      | crates.io, docs.rs        |
//! | `pypi`   | `crates/semiflow-py/README.md`   | PyPI (`semiflow-pde`)     |
//! | `npm`    | `crates/semiflow-wasm/README.md` | npm (`@semiflow/wasm`)    |
//!
//! Facts that would otherwise drift are computed, not typed: the version and MSRV
//! (workspace `Cargo.toml`), the runtime dependencies and feature flags
//! (`crates/semiflow/Cargo.toml`), the Python classes and functions (`#[pyclass]`
//! registrations, `__init__.pyi`) and the WASM class tables (`#[wasm_bindgen]`
//! structs, split lite/full by the `full` feature gate in `semiflow-wasm/src/lib.rs`).
//!
//! `cargo xtask readme --check` fails when a generated file differs from what the
//! source renders to (CI runs it). `cargo xtask readme-examples-js <package-dir>`
//! runs the Node.js examples of the npm README against a built package.

use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
    process,
};

use anyhow::{bail, Context, Result};

const SRC_DIR: &str = "docs/readme";
const TEMPLATE: &str = "README.src.md";
const REPO_BLOB: &str = "https://github.com/VolkovIlia/semiflow/blob/master/";
const GENERATED_HEADER: &str = "<!-- Generated by `cargo xtask readme` from \
docs/readme/README.src.md. Do not edit by hand: edit the source and regenerate. -->\n";

/// `(channel, output path relative to the workspace root)`.
const CHANNELS: [(&str, &str); 4] = [
    ("github", "README.md"),
    ("rust", "crates/semiflow/README.md"),
    ("pypi", "crates/semiflow-py/README.md"),
    ("npm", "crates/semiflow-wasm/README.md"),
];

/// Render (or with `--check`, verify) every channel README.
pub fn run(args: &[String]) -> Result<()> {
    let root = crate::workspace_root()?;
    let check = args.iter().any(|a| a == "--check");
    let facts = collect_facts(&root)?;
    let template = expand_includes(&root, &read(&root.join(SRC_DIR).join(TEMPLATE))?, 0)?;

    let mut stale = Vec::new();
    for (channel, out) in CHANNELS {
        let text = render(&template, channel, &facts)?;
        let path = root.join(out);
        if check {
            if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                stale.push(out);
            }
        } else {
            fs::write(&path, &text).with_context(|| format!("writing {out}"))?;
            println!("readme: wrote {out} ({channel})");
        }
    }
    if !stale.is_empty() {
        bail!(
            "readme: generated README(s) out of date: {}\n\
             Edit docs/readme/ (not the generated files) and run `cargo xtask readme`.",
            stale.join(", ")
        );
    }
    if check {
        println!(
            "readme: PASS — all {} READMEs match docs/readme/",
            CHANNELS.len()
        );
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

fn read(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))
}

/// Splice `<!-- include: file.md -->` lines (fragments may include fragments).
fn expand_includes(root: &Path, src: &str, depth: usize) -> Result<String> {
    if depth > 4 {
        bail!("readme: include nesting deeper than 4");
    }
    let mut out = String::new();
    for line in src.lines() {
        if let Some(name) = directive(line, "include:") {
            let fragment = read(&root.join(SRC_DIR).join(name))?;
            out.push_str(&expand_includes(
                root,
                strip_leading_comment(&fragment),
                depth + 1,
            )?);
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(out)
}

/// `<!-- KEY rest -->` → `Some(rest)` for a line consisting of that comment only.
fn directive<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let inner = line
        .trim()
        .strip_prefix("<!--")?
        .strip_suffix("-->")?
        .trim();
    inner.strip_prefix(key).map(str::trim)
}

/// Drop a leading `<!-- … -->` block (authoring notes in sources and fragments).
fn strip_leading_comment(src: &str) -> &str {
    let trimmed = src.trim_start();
    if trimmed.starts_with("<!--") {
        if let Some(end) = trimmed.find("-->") {
            let rest = &trimmed[end + 3..];
            // Directives are single-line comments; only strip a multi-line note.
            if trimmed[..end].contains('\n') {
                return rest.strip_prefix('\n').unwrap_or(rest);
            }
        }
    }
    src
}

fn render(template: &str, channel: &str, facts: &[(&'static str, String)]) -> Result<String> {
    let body = select_channel(strip_leading_comment(template), channel)?;
    let mut text = body;
    for (key, value) in facts {
        text = text.replace(&format!("{{{{{key}}}}}"), value);
    }
    if let Some(unknown) = find_unknown_placeholder(&text) {
        bail!("readme: unknown placeholder {{{{{unknown}}}}} in the {channel} README");
    }
    if channel != "github" {
        text = absolutize_links(&text);
    }
    Ok(format!("{GENERATED_HEADER}{}", tidy(&text)))
}

/// Keep lines outside `<!-- only: … -->` blocks, and inside the ones naming `channel`.
fn select_channel(src: &str, channel: &str) -> Result<String> {
    let mut stack: Vec<bool> = Vec::new();
    let mut out = String::new();
    for (no, line) in src.lines().enumerate() {
        if let Some(list) = directive(line, "only:") {
            if !list
                .split_whitespace()
                .all(|c| CHANNELS.iter().any(|(n, _)| *n == c))
            {
                bail!(
                    "readme: line {}: unknown channel in `{}`",
                    no + 1,
                    line.trim()
                );
            }
            stack.push(list.split_whitespace().any(|c| c == channel));
            continue;
        }
        if directive(line, "/only").is_some() {
            if stack.pop().is_none() {
                bail!(
                    "readme: line {}: `<!-- /only -->` without an opening block",
                    no + 1
                );
            }
            continue;
        }
        if stack.iter().all(|keep| *keep) {
            out.push_str(line);
            out.push('\n');
        }
    }
    if !stack.is_empty() {
        bail!("readme: unclosed `<!-- only: … -->` block");
    }
    Ok(out)
}

/// A `{{lower_snake}}` token left after substitution is a typo in the source.
/// (`{{SemiFlow}}` in BibTeX is not a placeholder: placeholders are lowercase.)
fn find_unknown_placeholder(text: &str) -> Option<&str> {
    let mut rest = text;
    while let Some(start) = rest.find("{{") {
        let after = &rest[start + 2..];
        if let Some(end) = after.find("}}") {
            let name = &after[..end];
            if !name.is_empty()
                && name
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            {
                return Some(name);
            }
        }
        rest = after;
    }
    None
}

/// `](relative/path)` → `](https://github.com/…/blob/master/relative/path)`.
fn absolutize_links(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(pos) = rest.find("](") {
        out.push_str(&rest[..pos + 2]);
        rest = &rest[pos + 2..];
        let is_relative = !(rest.starts_with("http://")
            || rest.starts_with("https://")
            || rest.starts_with('#')
            || rest.starts_with("mailto:"));
        if is_relative {
            out.push_str(REPO_BLOB);
            rest = rest.strip_prefix("./").unwrap_or(rest);
        }
    }
    out.push_str(rest);
    out
}

/// Collapse runs of blank lines and end with exactly one newline.
fn tidy(text: &str) -> String {
    let mut out = String::new();
    let mut blank_run = 0;
    for line in text.trim().lines() {
        if line.trim().is_empty() {
            blank_run += 1;
            if blank_run > 1 {
                continue;
            }
        } else {
            blank_run = 0;
        }
        out.push_str(line.trim_end());
        out.push('\n');
    }
    out
}

