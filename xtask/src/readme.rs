fn collect_facts(root: &Path) -> Result<Vec<(&'static str, String)>> {
    let workspace = read(&root.join("Cargo.toml"))?;
    let core = read(&root.join("crates/semiflow/Cargo.toml"))?;
    let version = toml_value(&workspace, "workspace.package", "version")?;
    let msrv = toml_value(&workspace, "workspace.package", "rust-version")?;
    let deps = toml_keys(&core, "dependencies");
    let py_functions = python_functions(root)?;
    let (lite, full) = wasm_classes(root)?;
    Ok(vec![
        ("pep440_version", pep440(&version)),
        ("version", version),
        ("msrv", msrv),
        ("runtime_dep_count", deps.len().to_string()),
        ("runtime_deps", backticked(&deps)),
        ("features_table", features_table(root, &core)?),
        ("py_class_count", python_class_count(root)?.to_string()),
        (
            "py_functions",
            backticked(
                &py_functions
                    .iter()
                    .map(|f| format!("{f}()"))
                    .collect::<Vec<_>>(),
            ),
        ),
        ("wasm_lite_table", class_table(&lite)),
        ("wasm_full_table", class_table(&full)),
    ])
}

fn backticked(items: &[String]) -> String {
    items
        .iter()
        .map(|i| format!("`{i}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Lines of the `[section]` table (up to the next `[…]` header).
fn toml_section<'a>(src: &'a str, section: &str) -> Vec<&'a str> {
    let header = format!("[{section}]");
    src.lines()
        .skip_while(|l| l.trim() != header)
        .skip(1)
        .take_while(|l| !l.trim_start().starts_with('['))
        .collect()
}

fn toml_value(src: &str, section: &str, key: &str) -> Result<String> {
    toml_section(src, section)
        .into_iter()
        .find_map(|l| {
            let (k, v) = l.split_once('=')?;
            (k.trim() == key).then(|| {
                v.split('#')
                    .next()
                    .unwrap_or("")
                    .trim()
                    .trim_matches('"')
                    .to_owned()
            })
        })
        .with_context(|| format!("readme: `{key}` not found in [{section}]"))
}

fn toml_keys(src: &str, section: &str) -> Vec<String> {
    toml_section(src, section)
        .into_iter()
        .filter_map(|l| {
            let l = l.trim();
            if l.is_empty() || l.starts_with('#') {
                return None;
            }
            l.split_once('=').map(|(k, _)| k.trim().to_owned())
        })
        .collect()
}

/// `0.13.1-beta` → `0.13.1b0`, `1.0.0-rc.2` → `1.0.0rc2` (PEP 440, as maturin does).
fn pep440(version: &str) -> String {
    let Some((base, pre)) = version.split_once('-') else {
        return version.to_owned();
    };
    let (label, num) = pre.split_once('.').unwrap_or((pre, "0"));
    let tag = match label {
        "alpha" | "a" => "a",
        "beta" | "b" => "b",
        "rc" => "rc",
        other => other,
    };
    format!("{base}{tag}{num}")
}

/// The feature table: names and defaults from Cargo.toml, prose from features.md.
fn features_table(root: &Path, core_manifest: &str) -> Result<String> {
    let section = toml_section(core_manifest, "features");
    let mut defaults = BTreeSet::new();
    let mut names = BTreeSet::new();
    for line in section {
        let Some((k, v)) = line.split_once('=') else {
            continue;
        };
        let k = k.trim();
        if k.starts_with('#') {
            continue;
        }
        if k == "default" {
            let list = v.split('#').next().unwrap_or("");
            for item in list
                .trim()
                .trim_start_matches('[')
                .trim_end_matches(']')
                .split(',')
            {
                let item = item.trim().trim_matches('"');
                if !item.is_empty() {
                    defaults.insert(item.to_owned());
                }
            }
        } else {
            names.insert(k.to_owned());
        }
    }

    let doc = read(&root.join(SRC_DIR).join("features.md"))?;
    let mut rows = Vec::new();
    let mut described = BTreeSet::new();
    for line in doc.lines().filter(|l| l.starts_with("| `")) {
        let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
        let [name, desc] = cells[..] else {
            bail!("readme: features.md: expected `| `name` | description |`: {line}");
        };
        let name = name.trim_matches('`');
        described.insert(name.to_owned());
        let default = if defaults.contains(name) { "yes" } else { "no" };
        rows.push(format!("| `{name}` | {default} | {desc} |"));
    }
    if described != names {
        bail!(
            "readme: docs/readme/features.md and crates/semiflow/Cargo.toml disagree.\n  \
             only in Cargo.toml: {:?}\n  only in features.md: {:?}",
            names.difference(&described).collect::<Vec<_>>(),
            described.difference(&names).collect::<Vec<_>>()
        );
    }
    Ok(format!(
        "| Feature | Default | Effect |\n|---------|---------|--------|\n{}",
        rows.join("\n")
    ))
}

/// Distinct `#[pyclass(name = "…")]` registrations (the Python-visible classes).
fn python_class_count(root: &Path) -> Result<usize> {
    let mut names = BTreeSet::new();
    for path in rust_files(&root.join("crates/semiflow-py/src"))? {
        let src = read(&path)?;
        for line in src.lines().filter(|l| l.contains("pyclass(")) {
            if let Some(rest) = line.split("name").nth(1) {
                if let Some(name) = rest.split('"').nth(1) {
                    names.insert(name.to_owned());
                }
            }
        }
    }
    Ok(names.len())
}

/// Module-level functions declared in the shipped `__init__.pyi` stub.
fn python_functions(root: &Path) -> Result<Vec<String>> {
    let stub = read(&root.join("crates/semiflow-py/python/semiflow/__init__.pyi"))?;
    Ok(stub
        .lines()
        .filter_map(|l| l.strip_prefix("def "))
        .filter_map(|l| l.split('(').next())
        .map(str::to_owned)
        .collect())
}

fn rust_files(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut files = Vec::new();
    for entry in walkdir::WalkDir::new(dir) {
        let entry = entry?;
        if entry.path().extension().is_some_and(|e| e == "rs") {
            files.push(entry.into_path());
        }
    }
    files.sort();
    Ok(files)
}

/// `(js_name, first doc line)` of every exported WASM class, split into the
/// default npm build and the `full`-feature build.
type ClassList = Vec<(String, String)>;

fn wasm_classes(root: &Path) -> Result<(ClassList, ClassList)> {
    let src_dir = root.join("crates/semiflow-wasm/src");
    let lib = read(&src_dir.join("lib.rs"))?;
    let lines: Vec<&str> = lib.lines().collect();
    let mut full_modules = BTreeSet::new();
    for pair in lines.windows(2) {
        if pair[0].trim() == "#[cfg(feature = \"full\")]" {
            if let Some(m) = pair[1].trim().strip_prefix("mod ") {
                full_modules.insert(m.trim_end_matches(';').to_owned());
            }
        }
    }

    // A file spliced in with `include!("x.rs")` inherits the gate of its includer.
    let files = rust_files(&src_dir)?;
    for path in &files {
        let stem = file_stem(path);
        if full_modules.contains(&stem) {
            for line in read(path)?.lines() {
                if let Some(inc) = line.trim().strip_prefix("include!(\"") {
                    full_modules.insert(
                        inc.trim_end_matches("\");")
                            .trim_end_matches(".rs")
                            .to_owned(),
                    );
                }
            }
        }
    }

    let (mut lite, mut full) = (Vec::new(), Vec::new());
    for path in &files {
        let target = if full_modules.contains(&file_stem(path)) {
            &mut full
        } else {
            &mut lite
        };
        target.extend(wasm_exports(&read(path)?));
    }
    lite.sort();
    full.sort();
    Ok((lite, full))
}

fn file_stem(path: &Path) -> String {
    path.file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or_default()
        .to_owned()
}

/// Column-0 `#[wasm_bindgen…]` directly above `pub struct X`.
fn wasm_exports(src: &str) -> ClassList {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        if !line.starts_with("#[wasm_bindgen") || line.contains("js_class") {
            continue;
        }
        let Some(next) = lines[i + 1..].iter().find(|l| !l.trim().is_empty()) else {
            continue;
        };
        let Some(rest) = next.trim().strip_prefix("pub struct ") else {
            continue;
        };
        let struct_name: String = rest
            .chars()
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect();
        let js_name = line
            .split("js_name")
            .nth(1)
            .and_then(|r| r.split('"').nth(1))
            .map_or(struct_name, str::to_owned);
        out.push((js_name, doc_summary(&lines[..i])));
    }
    out
}

/// First paragraph of the `///` block right above the attribute, without the
/// internal cross-references (ADR / § / milestone / internal version tags).
fn doc_summary(before: &[&str]) -> String {
    let mut block: Vec<&str> = before
        .iter()
        .rev()
        .take_while(|l| l.trim_start().starts_with("///") || l.trim_start().starts_with("#["))
        .filter(|l| l.trim_start().starts_with("///"))
        .map(|l| l.trim_start().trim_start_matches("///").trim())
        .collect();
    block.reverse();
    let paragraph: Vec<&str> = block
        .into_iter()
        .skip_while(|l| l.is_empty())
        .take_while(|l| !l.is_empty() && !l.starts_with('#') && !l.starts_with("```"))
        .collect();
    let text = paragraph.join(" ").replace("[`", "`").replace("`]", "`");
    let cleaned = strip_internal_refs(&text);
    let cleaned = cleaned.trim().trim_end_matches([':', ',']).trim();
    cleaned.replace('|', "\\|")
}

/// Drop parenthesised items such as `ADR-0138`, `§21.9`, `math §50`, `M11`,
/// `Wave F`, `v8.3.0` and bare internal version tags like `v9.0.0-beta`.
fn strip_internal_refs(text: &str) -> String {
    fn internal(item: &str) -> bool {
        let item = item.trim();
        let versioned = |s: &str| {
            s.strip_prefix('v')
                .is_some_and(|r| r.chars().next().is_some_and(|c| c.is_ascii_digit()))
        };
        item.starts_with("ADR-")
            || item.starts_with('§')
            || item.starts_with("math §")
            || item.starts_with("Wave ")
            || versioned(item)
            || (item.starts_with('M')
                && item.len() > 1
                && item[1..].chars().all(|c| c.is_ascii_digit()))
    }
    let mut out = String::new();
    let mut rest = text;
    while let Some(open) = rest.find('(') {
        out.push_str(&rest[..open]);
        let Some(close) = rest[open..].find(')') else {
            out.push_str(&rest[open..]);
            return out;
        };
        let inner = &rest[open + 1..open + close];
        let kept: Vec<&str> = inner
            .split(',')
            .filter(|i| !internal(i))
            .map(str::trim)
            .collect();
        if !kept.is_empty() {
            out.push('(');
            out.push_str(&kept.join(", "));
            out.push(')');
        } else {
            // drop the space that preceded the removed group
            while out.ends_with(' ') {
                out.pop();
            }
        }
        rest = &rest[open + close + 1..];
    }
    out.push_str(rest);
    // bare tags outside parentheses, e.g. "evaluator v8.1.0 for"
    out.split(' ')
        .filter(|w| {
            !(w.starts_with('v')
                && w[1..].chars().next().is_some_and(|c| c.is_ascii_digit())
                && w.contains('.'))
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn class_table(classes: &ClassList) -> String {
    let mut out = String::from("| Class | Description |\n|-------|-------------|\n");
    for (name, desc) in classes {
        out.push_str(&format!("| `{name}` | {desc} |\n"));
    }
    out.trim_end().to_owned()
}

