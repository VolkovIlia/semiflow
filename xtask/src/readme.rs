/// Run every ```js block of the npm README (except `<!-- readme-test: skip` ones)
/// with Node.js, resolving `@semiflow/wasm` to the built package in `args[0]`.
pub fn run_js_examples(args: &[String]) -> Result<()> {
    let root = crate::workspace_root()?;
    let Some(pkg) = args.first() else {
        bail!("usage: cargo xtask readme-examples-js <built-package-dir, e.g. dist/npm>");
    };
    let pkg = fs::canonicalize(root.join(pkg)).with_context(|| format!("package dir {pkg}"))?;
    let readme = read(&root.join("crates/semiflow-wasm/README.md"))?;
    let blocks = code_blocks(&readme, "js");
    let work = root.join("target").join("readme-examples");
    fs::create_dir_all(&work)?;

    let mut ran = 0;
    for (i, block) in blocks.iter().enumerate() {
        let script = block.replace(
            "require('@semiflow/wasm')",
            &format!("require({:?})", pkg.display().to_string()),
        );
        let file = work.join(format!("example-{i}.cjs"));
        fs::write(&file, script)?;
        let status = process::Command::new("node").arg(&file).status()?;
        if !status.success() {
            bail!(
                "readme-examples-js: example {i} failed ({})",
                file.display()
            );
        }
        ran += 1;
    }
    if ran == 0 {
        bail!("readme-examples-js: no runnable ```js blocks found");
    }
    println!("readme-examples-js: PASS — {ran} example(s)");
    Ok(())
}

/// Bodies of fenced ```lang blocks not preceded by a `readme-test: skip` marker.
pub fn code_blocks(markdown: &str, lang: &str) -> Vec<String> {
    let mut blocks = Vec::new();
    // Some((keep, body)) while inside a ```lang block.
    let mut current: Option<(bool, String)> = None;
    let mut skip_next = false;
    for line in markdown.lines() {
        if let Some((keep, body)) = current.as_mut() {
            if line.trim_start().starts_with("```") {
                if *keep {
                    blocks.push(std::mem::take(body));
                }
                current = None;
            } else {
                body.push_str(line);
                body.push('\n');
            }
        } else if line.contains("<!-- readme-test: skip") {
            skip_next = true;
        } else if line.trim_start().strip_prefix("```") == Some(lang) {
            current = Some((!skip_next, String::new()));
            skip_next = false;
        } else if !line.trim().is_empty() {
            skip_next = false;
        }
    }
    blocks
}
